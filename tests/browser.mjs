/* Run using an available Playwright installation; runtime app has no JS deps. */
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdirSync,readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.COPPER_PLAYWRIGHT_MODULE || 'playwright');
const url=process.argv[2];assert(url && new URL(url).hostname==='127.0.0.1');
const browser=await chromium.launch({headless:true,...(process.env.COPPER_BROWSER_EXECUTABLE?{executablePath:process.env.COPPER_BROWSER_EXECUTABLE}:{})});
const page=await browser.newPage({viewport:{width:1520,height:1020}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
mkdirSync('test-results',{recursive:true});
try {
  await page.goto(url);
  await page.waitForFunction(()=>document.querySelectorAll('.entity').length===4);
  // Exercise hit-testing on the board itself, independent of explorer selection.
  await page.locator('#fit').click();await page.locator('#mode-net').click();
  const initialBox=await page.locator('#board-canvas').boundingBox();
  const initialZoom=Math.min((initialBox.width-80)/50,(initialBox.height-80)/35);
  const padX=initialBox.x+initialBox.width/2+(23.2-25)*initialZoom;
  const padY=initialBox.y+(initialBox.height-20)/2+(16-17.5)*initialZoom;
  await page.mouse.click(padX,padY);
  assert((await page.locator('#selection-detail').textContent()).includes('SENSOR_SCL'));
  await page.locator('#mode-component').click();
  await page.getByRole('button',{name:'U1 Controller',exact:true}).click();
  await page.locator('#observation').fill('The package exits cross in front of U1.');
  await page.locator('#desired').fill('Keep exit order while assigning routing corridors.');
  await page.locator('#save-note').click();
  assert.equal(await page.locator('.note-row').count(),1);
  await page.locator('#tab-nets').click();
  await page.getByRole('button',{name:'SENSOR_SCL 2 pads',exact:true}).click();
  await page.locator('#observation').fill('SCL takes a detour.');
  await page.locator('#category').selectOption('routing');
  await page.locator('#save-note').click();
  await page.locator('#fit').click();await page.locator('#mode-region').click();
  const box=await page.locator('#board-canvas').boundingBox();
  await page.mouse.move(box.x+box.width*.45,box.y+box.height*.35);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.65,box.y+box.height*.65);await page.mouse.up();
  assert((await page.locator('#selection-detail').textContent()).includes('Region'));
  await page.locator('#observation').fill('Reserve this region before area routing.');
  await page.locator('#desired').fill('Add a corridor planning heuristic.');await page.locator('#save-note').click();
  assert.equal(await page.locator('.note-row').count(),3);
  const downloadPromise=page.waitForEvent('download');await page.locator('#export-review').click();
  const download=await downloadPromise;await download.saveAs('test-results/browser.review.json');
  const review=JSON.parse(readFileSync('test-results/browser.review.json'));
  assert.equal(review.annotations.length,3);assert.equal(review.annotations[0].context.components[0].source_path,'control.U1');
  assert.equal(review.annotations[1].context.nets[0].tracks.length,3);assert(review.annotations[2].selection.region);
  await page.reload();await page.waitForFunction(()=>document.querySelectorAll('.note-row').length===3);
  await page.locator('.note').first().click();await page.locator('#observation').fill('Edited package exit observation.');await page.locator('#save-note').click();
  assert((await page.locator('.note-title').first().textContent()).includes('Edited'));
  await page.locator('#review-file').setInputFiles('test-results/browser.review.json');
  await page.waitForFunction(()=>document.querySelector('.note-title')?.textContent==='The package exits cross in front of U1.');
  await page.locator('#fit').click();await page.screenshot({path:'test-results/review-ui.png',fullPage:true});
  await page.locator('#layer-list input').last().uncheck();
  await page.locator('#show-guides').check();
  await page.locator('#isolate').check();
  await page.locator('#search').fill('DOES_NOT_EXIST');assert.equal(await page.locator('.entity').count(),0);
  await page.locator('#search').fill('');
  await page.locator('.delete-note').last().click();assert.equal(await page.locator('.note-row').count(),2);
  assert.deepEqual(errors,[]);
  console.log('PASS: component/net/region notes, edit/delete, JSON download/reload, local persistence, layers, guides and search');
}finally{await browser.close();}
